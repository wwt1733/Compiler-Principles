class Ctx:
    def __init__(self, doc, off, nums):
        self.doc = doc
        self.off = off
        self.nums = nums

    def _h(self, level, text):
        level = min(level + self.off, 4)
        [h1, h2, h3, h4][level - 1](self.doc, text)

    def title(self, text):
        self._h(1, text)

    def appendix_title(self, text):
        """附录标题：单独成册时是 1 级标题；作为报告附录时降为 2 级。"""
        self._h(1 if self.off == 0 else 2, text)

    def sec(self, text):
        self._h(2, text)

    def sub(self, text):
        self._h(3, text)

    def p(self, text, indent=True):
        p(self.doc, text, indent=indent)

    def item(self, text):
        item(self.doc, text, left_pt=24.0, hang_pt=12.0)

    def code(self, text):
        code_block(self.doc, text, size=8.5)

    def fig(self, num, path, cap, width=TEXT_WIDTH_CM):
        figure_n(self.doc, num, os.path.join(IMG, path + ".png"), cap, width_cm=width)

    def table(self, num, title, headers, rows, widths=None, size=9.0, note=None):
        table_n(self.doc, num, title, headers, rows, widths=widths, font_size=size, note=note)


