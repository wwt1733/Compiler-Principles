def section4(doc):
    h1(doc, "四、实验总结（心得体会）")
    p(doc, "这次课程设计是我第一次把“编译原理”从纸上的推导做成一个真正能用的系统。两部分任务"
           "加起来写了约 2.6 万行 C++，界面有 15 个功能页签，最后能完整跑通“正则表达式 → 可执行"
           "的词法分析程序”和“BNF → LALR(1) 分析表 → 语法树 → 四元式”两条链路。回头看，收获"
           "最大的并不是某个算法，而是“怎么确认自己是对的”。")
    p(doc, "第一点体会是**规格必须当成数据来处理**。以前做实验，正则表达式是写在代码里的常量；这次"
           "要支持用户输入任意规格，就不得不把“名字_编码[L]”“宏定义”“注释/关键字”这些约定"
           "全部实现出来。真正做起来才发现任务书里的约定并不自洽：TINY 的单词表里没有 `>=`、"
           "没有 `^`、也没有圆括号，但它的 BNF 里偏偏要用到，样例程序 `sample.tny` 里还写着 "
           "`(xXx + 1) * 1`。最后只能按“先让样例程序零错误通过”的原则补上编码，并把补的理由、"
           "补的位置、会影响哪些断言全部记进文档 —— 这让我第一次体会到什么叫“接口一旦冻结，"
           "改动要全仓库同步”。")
    p(doc, "第二点体会是**性能问题会伪装成正确性问题**。最初子集构造一次要 31 秒，点一下按钮"
           "窗口就“未响应”，我一度以为程序卡死了。后来通过自带的耗时报表才定位到：五条看起来"
           "无关的测试其实是同一条流水线跑了五遍，而流水线里最慢的就是子集构造。把 `move` 与 ε "
           "闭包的边表预建索引后，单次从 31 秒降到约 9 秒，整套自测从 192 秒降到 54 秒。更重要的"
           "是学会了：**任何超过 1~2 秒的同步计算都必须让消息队列走一次**，否则用户看到的就是"
           "“卡死”。")
    p(doc, "第三点体会是**界面上的每个字都要能对得上代码**。调试过程中遇到过好几处“看起来"
           "正常、其实错得离谱”的界面问题：跑完整条词法流水线后，页签②里显示的仍是上一次构造的 "
           "NFA；状态栏一直挂着“正在构造 DFA…已生成 N 个状态”；甚至还挂着一句阶段 0 时的"
           "“当前进度：阶段 0（工程骨架）”。这些问题都不影响算法正确性，但会直接误导评阅的人。"
           "后来养成了一个习惯：每加一个界面文案，就想一遍“它在什么情况下会是错的”，并加上"
           "断言守住它。")
    p(doc, "第四点体会是**测试要能自己发现问题**。到最后我已经不敢靠“点点看”来判断改对了没有，"
           "于是把断言分成两层：一层跑算法（304 项），一层跑界面（346 项），再加上与老师参考数据"
           "的逐词比对。有好几次改动在界面上看不出来，是断言直接报红拦住的，例如“双圈结点数与"
           "接受态数不符”“语法树同层结点框重叠”“字母表仍是 256 个字节”。写测试的时间不比写"
           "功能少，但它让我敢改代码。")
    p(doc, "不足也有：mini-C 的 LALR(1) 分析表仍有 1 处冲突（源于任务书文法本身），目前只做了"
           "明确的冲突报告与默认消解，没有实现“报错并拒绝生成”；四元式只做了四元式一种形式，"
           "没有做三元组与伪代码；界面虽然功能齐全，但样式仍偏朴素。这些都记在了文档的“遗留"
           "问题”里，作为后续改进方向。")
    p(doc, "总的来说，这门课程设计让我把“编译原理”的每个算法都亲手实现了一遍，也第一次完整"
           "经历了需求分析、设计、编码、测试、文档的软件工程流程。最大的收获是：**写编译器的"
           "过程，本质上是不断把“我觉得对”变成“我能证明它对”的过程。**")


