    h3(doc, "3.1.1  输入数据格式需求")
    p(doc, "本系统要读三类输入文件，均由用户以文本方式编辑，格式如下（全部统一 UTF-8 编码）：")
    p(doc, "**（1）单词规格文件**：一行一条定义，`#` 后为注释。三种写法：`digit=[0-9]` 形式为"
           "**宏定义**（只做替换，不建自动机）；`Num_100=…`、`Comment_102=…` 形式为**需要生成 "
           "DFA 的规则**，下划线后的数字即单词编码，编码后加 `L` 表示连续分配；"
           "`Keyword103L=if|then|else` 形式为**关键字表**，不建自动机，按声明顺序占用连续编码。")
    p(doc, "**（2）BNF 文法文件**：一行一条产生式，写作 `左部 -> 右部1 | 右部2`，符号之间以空白"
           "分隔，`#`（mini-C 中为 `@`）表示空串；第一个非终结符即开始符号，载入后程序自动"
           "增广 `S' -> S`。")
    p(doc, "**（3）语法树结构（语义动作）文件**：一行对应一条产生式，行序与文法文件中产生式的"
           "出现顺序一致；用 `;` 分成若干“建结点组”，最后一组的结果即本次规约返回的结点。"
           "本项目采用带前缀字母的紧凑写法，例如 `L 1 ; L` 表示“先为右部第 1 项建一个以左部"
           "符号为标签的结点，再建一个无子结点的左部结点”；`R0 2` 表示“标签取右部第 0 项的"
           "结点、子结点为第 2 项”。（老师提供的参考数据用纯数字三元组书写，实测无法无歧义"
           "解析，本项目因此改用带前缀的写法，语义结果与参考数据一致，详见 3.3.3 节。）")


