def img(name):
    return os.path.join(IMG, name + ".png")


class Ctx:
    """把“标题层级偏移”与“图表编号器”打包，便于同一份内容两处复用。"""

    def __init__(self, doc, off, nums):
        self.doc = doc
        self.off = off
        self.nums = nums          # 每章一个 Num 实例组成的列表

    def _h(self, level, text):
        level = min(level + self.off, 4)
        [h1, h2, h3, h4][level - 1](self.doc, text)

    def title(self, text):
        self._h(1, text)

    def sec(self, text):
        self._h(2, text)

    def sub(self, text):
        self._h(3, text)

    def p(self, text, indent=True):
        p(self.doc, text, indent=indent)

    def item(self, text):
        item(self.doc, text, left_pt=24.0, hang_pt=12.0)

    def code(self, text):
        code_block(self.doc, text, size=8.5)

    def fig(self, num, path, cap, width=14.6):
        figure_n(self.doc, num, img(path), cap, width_cm=width)

    def table(self, num, title, headers, rows, widths=None, size=9.5, note=None):
        table_n(self.doc, num, title, headers, rows, widths=widths, font_size=size, note=note)


